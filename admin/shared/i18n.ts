export const dict: Record<Lang, Record<string, string>> = { zh, en };

/** 字典查取：当前语言 → 另一语言 → 键名 */
export function createT(lang: Lang): (key: string) => string {
  const other: Lang = lang === 'zh' ? 'en' : 'zh';
  return (key: string) => dict[lang][key] ?? dict[other][key] ?? key;
}

/** 初始语言：localStorage 记忆 > 浏览器语言 > zh */
export function detectLang(navigatorLanguage: string, stored: string | null): Lang {
  if (stored === 'zh' || stored === 'en') return stored;
  return navigatorLanguage.toLowerCase().startsWith('en') ? 'en' : 'zh';
}
